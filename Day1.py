# what is dynamic typing in python?
# python is a dynamically typed language, which means that you do not need to declare the type of a variable when you create it. The type of a variable is determined at runtime based on the value assigned to it. This allows for more flexibility in coding, as you can change the type of a variable simply by assigning it a new value of a different type.
